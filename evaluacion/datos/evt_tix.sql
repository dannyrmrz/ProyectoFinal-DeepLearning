CREATE TABLE vnu (
  vnu_id INT PRIMARY KEY,
  vnu_nm VARCHAR(60) NOT NULL COMMENT 'Venue name',
  city VARCHAR(40) NOT NULL,
  cap INT NOT NULL COMMENT 'Maximum capacity'
) COMMENT='Venues';

CREATE TABLE artst (
  artst_id INT PRIMARY KEY,
  artst_nm VARCHAR(60) NOT NULL,
  genre VARCHAR(20),
  ctry CHAR(2) COMMENT 'ISO country code'
) COMMENT='Artists';

CREATE TABLE evt (
  evt_id INT PRIMARY KEY,
  evt_nm VARCHAR(80) NOT NULL,
  vnu_id INT NOT NULL,
  artst_id INT NOT NULL,
  evt_dt DATETIME NOT NULL COMMENT 'Event start date and time',
  base_prc DECIMAL(8,2) NOT NULL COMMENT 'Base ticket price in USD',
  FOREIGN KEY (vnu_id) REFERENCES vnu(vnu_id),
  FOREIGN KEY (artst_id) REFERENCES artst(artst_id)
) COMMENT='Events';

CREATE TABLE cust (
  cust_id INT PRIMARY KEY,
  fname VARCHAR(40) NOT NULL,
  lname VARCHAR(40) NOT NULL,
  email VARCHAR(80),
  city VARCHAR(40),
  reg_dt DATE COMMENT 'Registration date'
) COMMENT='Customers';

CREATE TABLE tkt_ord (
  ord_id INT PRIMARY KEY,
  cust_id INT NOT NULL,
  ord_dt DATETIME NOT NULL,
  pay_mthd VARCHAR(10) COMMENT 'CARD, CASH or PAYPAL',
  sts VARCHAR(10) NOT NULL COMMENT 'PAID or REFUNDED',
  FOREIGN KEY (cust_id) REFERENCES cust(cust_id)
) COMMENT='Ticket orders';

CREATE TABLE tkt (
  tkt_id INT PRIMARY KEY,
  ord_id INT NOT NULL,
  evt_id INT NOT NULL,
  seat_cls VARCHAR(5) NOT NULL COMMENT 'GEN or VIP',
  prc DECIMAL(8,2) NOT NULL COMMENT 'Price paid for the ticket in USD',
  FOREIGN KEY (ord_id) REFERENCES tkt_ord(ord_id),
  FOREIGN KEY (evt_id) REFERENCES evt(evt_id)
) COMMENT='Tickets sold';


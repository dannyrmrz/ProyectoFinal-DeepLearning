CREATE TABLE sucursales (
  id_sucursal INT PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  ciudad VARCHAR(40) NOT NULL,
  fecha_apertura DATE COMMENT 'Fecha en que abrió la sucursal'
) COMMENT='Sucursales de la cadena de farmacias';

CREATE TABLE categorias (
  id_categoria INT PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL
) COMMENT='Categorías de producto';

CREATE TABLE proveedores (
  id_proveedor INT PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  pais VARCHAR(40) COMMENT 'País de origen del proveedor'
);

CREATE TABLE productos (
  id_producto INT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  id_categoria INT NOT NULL,
  id_proveedor INT NOT NULL,
  precio DECIMAL(8,2) NOT NULL COMMENT 'Precio de venta al público en quetzales',
  requiere_receta TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 si necesita receta médica',
  FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria),
  FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor)
);

CREATE TABLE empleados (
  id_empleado INT PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL,
  apellido VARCHAR(40) NOT NULL,
  id_sucursal INT NOT NULL,
  puesto VARCHAR(30) COMMENT 'cajero, farmaceutico o gerente',
  salario DECIMAL(10,2) COMMENT 'Salario mensual en quetzales',
  fecha_ingreso DATE,
  id_jefe INT NULL COMMENT 'Empleado al que reporta; NULL si no tiene jefe',
  FOREIGN KEY (id_sucursal) REFERENCES sucursales(id_sucursal),
  FOREIGN KEY (id_jefe) REFERENCES empleados(id_empleado)
);

CREATE TABLE ventas (
  id_venta INT PRIMARY KEY,
  id_sucursal INT NOT NULL,
  id_empleado INT NOT NULL COMMENT 'Empleado que registró la venta',
  fecha DATETIME NOT NULL,
  metodo_pago VARCHAR(15) COMMENT 'efectivo, tarjeta o transferencia',
  FOREIGN KEY (id_sucursal) REFERENCES sucursales(id_sucursal),
  FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado)
) COMMENT='Encabezado de cada venta';

CREATE TABLE detalle_venta (
  id_venta INT NOT NULL,
  id_producto INT NOT NULL,
  cantidad INT NOT NULL,
  precio_unitario DECIMAL(8,2) NOT NULL COMMENT 'Precio cobrado por unidad en esa venta',
  PRIMARY KEY (id_venta, id_producto),
  FOREIGN KEY (id_venta) REFERENCES ventas(id_venta),
  FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
) COMMENT='Productos incluidos en cada venta';

